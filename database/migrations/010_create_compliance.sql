-- 010_create_compliance.sql — statutory acts, rules, regulations, notifications, legal register
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS compliance_acts (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  act_name          VARCHAR(500) NOT NULL,
  short_name        VARCHAR(100) DEFAULT NULL,
  act_number        VARCHAR(100) DEFAULT NULL,
  act_year          INT DEFAULT NULL,
  jurisdiction      ENUM('Central','State','International') NOT NULL DEFAULT 'Central',
  state_name        VARCHAR(100) DEFAULT NULL,
  ministry          VARCHAR(255) DEFAULT NULL,
  department        VARCHAR(255) DEFAULT NULL,
  enactment_date    DATE DEFAULT NULL,
  effective_date    DATE DEFAULT NULL,
  last_amended_date DATE DEFAULT NULL,
  applicability_criteria TEXT,
  industry_applicability VARCHAR(500) DEFAULT NULL,
  employee_threshold VARCHAR(100) DEFAULT NULL,
  summary           TEXT,
  full_text         LONGTEXT,
  official_source_url VARCHAR(500) DEFAULT NULL,
  status            ENUM('active','repealed','amended','draft') NOT NULL DEFAULT 'active',
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by        BIGINT UNSIGNED DEFAULT NULL,
  updated_by        BIGINT UNSIGNED DEFAULT NULL,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_ca_name (act_name),
  KEY idx_ca_short (short_name),
  KEY idx_ca_jurisdiction (jurisdiction),
  KEY idx_ca_status (status),
  CONSTRAINT fk_ca_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS compliance_rules (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  act_id          BIGINT UNSIGNED NOT NULL,
  rule_number     VARCHAR(50) DEFAULT NULL,
  rule_title      VARCHAR(500) NOT NULL,
  rule_text       LONGTEXT,
  compliance_type ENUM('Mandatory','Recommended','Best Practice') NOT NULL DEFAULT 'Mandatory',
  frequency       ENUM('One-time','Daily','Weekly','Monthly','Quarterly','Half-Yearly','Annual','Bi-Annual','Event-based') DEFAULT NULL,
  due_day_of_month INT DEFAULT NULL,
  responsible_role VARCHAR(150) DEFAULT NULL,
  penalty_details  TEXT,
  evidence_required TEXT,
  applicability    TEXT,
  status          ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by      BIGINT UNSIGNED DEFAULT NULL,
  updated_by      BIGINT UNSIGNED DEFAULT NULL,
  deleted_at      DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_cr_act (act_id),
  KEY idx_cr_frequency (frequency),
  KEY idx_cr_status (status),
  CONSTRAINT fk_cr_act FOREIGN KEY (act_id) REFERENCES compliance_acts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS compliance_regulations (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  act_id            BIGINT UNSIGNED DEFAULT NULL,
  rule_id           BIGINT UNSIGNED DEFAULT NULL,
  regulation_name   VARCHAR(500) NOT NULL,
  regulation_number VARCHAR(100) DEFAULT NULL,
  issuing_authority VARCHAR(255) DEFAULT NULL,
  issue_date        DATE DEFAULT NULL,
  effective_date    DATE DEFAULT NULL,
  scope             TEXT,
  obligations       LONGTEXT,
  reporting_authority VARCHAR(255) DEFAULT NULL,
  reporting_frequency VARCHAR(100) DEFAULT NULL,
  penalty_provision TEXT,
  status            ENUM('active','superseded','withdrawn') NOT NULL DEFAULT 'active',
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by        BIGINT UNSIGNED DEFAULT NULL,
  updated_by        BIGINT UNSIGNED DEFAULT NULL,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_crg_act (act_id),
  KEY idx_crg_rule (rule_id),
  KEY idx_crg_status (status),
  CONSTRAINT fk_crg_act FOREIGN KEY (act_id) REFERENCES compliance_acts(id) ON DELETE SET NULL,
  CONSTRAINT fk_crg_rule FOREIGN KEY (rule_id) REFERENCES compliance_rules(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS compliance_notifications (
  id                  BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  notification_number VARCHAR(150) NOT NULL,
  title               VARCHAR(500) NOT NULL,
  notification_date   DATE DEFAULT NULL,
  issuing_authority   VARCHAR(255) DEFAULT NULL,
  act_id              BIGINT UNSIGNED DEFAULT NULL,
  gazette_reference   VARCHAR(255) DEFAULT NULL,
  subject             TEXT,
  body                LONGTEXT,
  effective_date      DATE DEFAULT NULL,
  applicability       TEXT,
  action_required     TEXT,
  status              ENUM('active','superseded','withdrawn') NOT NULL DEFAULT 'active',
  created_at          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by          BIGINT UNSIGNED DEFAULT NULL,
  updated_by          BIGINT UNSIGNED DEFAULT NULL,
  deleted_at          DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_cn_act (act_id),
  KEY idx_cn_date (notification_date),
  KEY idx_cn_status (status),
  CONSTRAINT fk_cn_act FOREIGN KEY (act_id) REFERENCES compliance_acts(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Legal Register: an employer's licence/certificate/permit with validity + reminders.
CREATE TABLE IF NOT EXISTS compliance_documents (
  id                  BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid                VARCHAR(36) NOT NULL,
  document_name       VARCHAR(500) NOT NULL,
  document_type       ENUM('Licence','Certificate','Permit','Registration','Return','Approval','Agreement','Insurance','Other')
                      NOT NULL DEFAULT 'Licence',
  employer_id         BIGINT UNSIGNED NOT NULL,
  unit_id             BIGINT UNSIGNED DEFAULT NULL,
  act_id              BIGINT UNSIGNED DEFAULT NULL,
  rule_id             BIGINT UNSIGNED DEFAULT NULL,
  document_number     VARCHAR(150) DEFAULT NULL,
  issuing_authority   VARCHAR(255) DEFAULT NULL,
  issue_date          DATE DEFAULT NULL,
  expiry_date         DATE DEFAULT NULL,
  validity_period_days INT DEFAULT NULL,
  remind_days_before  INT NOT NULL DEFAULT 30,
  reminder_sent_at    DATETIME DEFAULT NULL,
  renewal_responsibility VARCHAR(200) DEFAULT NULL,
  fee_amount          DECIMAL(15,2) DEFAULT NULL,
  compliance_status   ENUM('Valid','Expiring Soon','Expired','Applied for Renewal','Not Applicable') NOT NULL DEFAULT 'Valid',
  file_id             BIGINT UNSIGNED DEFAULT NULL,
  file_path           VARCHAR(500) DEFAULT NULL,
  notes               TEXT,
  is_verified         BOOLEAN NOT NULL DEFAULT FALSE,
  verified_by         BIGINT UNSIGNED DEFAULT NULL,
  verified_at         DATETIME DEFAULT NULL,
  created_at          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by          BIGINT UNSIGNED DEFAULT NULL,
  updated_by          BIGINT UNSIGNED DEFAULT NULL,
  deleted_at          DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_cd_uuid (uuid),
  KEY idx_cd_employer (employer_id),
  KEY idx_cd_type (document_type),
  KEY idx_cd_expiry (expiry_date),
  KEY idx_cd_status (compliance_status),
  CONSTRAINT fk_cd_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_cd_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_cd_act FOREIGN KEY (act_id) REFERENCES compliance_acts(id) ON DELETE SET NULL,
  CONSTRAINT fk_cd_rule FOREIGN KEY (rule_id) REFERENCES compliance_rules(id) ON DELETE SET NULL,
  CONSTRAINT fk_cd_verified_by FOREIGN KEY (verified_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Applicability matrix: which act/rule applies to which employer, and compliance state.
CREATE TABLE IF NOT EXISTS employer_compliance_mapping (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  employer_id       BIGINT UNSIGNED NOT NULL,
  act_id            BIGINT UNSIGNED DEFAULT NULL,
  rule_id           BIGINT UNSIGNED DEFAULT NULL,
  is_applicable     BOOLEAN NOT NULL DEFAULT TRUE,
  compliance_status ENUM('Compliant','Partially Compliant','Non-Compliant','Under Review','Not Assessed')
                    NOT NULL DEFAULT 'Not Assessed',
  last_assessed_at  DATETIME DEFAULT NULL,
  assessed_by       BIGINT UNSIGNED DEFAULT NULL,
  next_due_date     DATE DEFAULT NULL,
  remarks           TEXT,
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ecm (employer_id, act_id, rule_id),
  KEY idx_ecm_employer (employer_id),
  CONSTRAINT fk_ecm_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_ecm_act FOREIGN KEY (act_id) REFERENCES compliance_acts(id) ON DELETE CASCADE,
  CONSTRAINT fk_ecm_rule FOREIGN KEY (rule_id) REFERENCES compliance_rules(id) ON DELETE CASCADE,
  CONSTRAINT fk_ecm_assessed_by FOREIGN KEY (assessed_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
