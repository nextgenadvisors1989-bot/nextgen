-- 005_create_auditors.sql — auditor registry, auditor types, auditor↔module mapping
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS auditor_types (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name              VARCHAR(150) NOT NULL,
  code              VARCHAR(50)  NOT NULL,
  description       TEXT,
  specialization    VARCHAR(200) DEFAULT NULL,
  default_module_id BIGINT UNSIGNED DEFAULT NULL,
  status            ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_at_name (name),
  UNIQUE KEY uq_at_code (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS auditors (
  id                  BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid                VARCHAR(36) NOT NULL,
  user_id             BIGINT UNSIGNED DEFAULT NULL,
  auditor_code        VARCHAR(50) NOT NULL,
  name                VARCHAR(200) NOT NULL,
  email               VARCHAR(255) NOT NULL,
  mobile              VARCHAR(20)  DEFAULT NULL,
  alternate_mobile    VARCHAR(20)  DEFAULT NULL,
  auditor_type_id     BIGINT UNSIGNED DEFAULT NULL,
  role_title          VARCHAR(150) DEFAULT NULL,
  specialization      VARCHAR(200) DEFAULT NULL,
  qualification       VARCHAR(255) DEFAULT NULL,
  experience_years    DECIMAL(4,1) DEFAULT NULL,
  address             TEXT,
  city                VARCHAR(100) DEFAULT NULL,
  state               VARCHAR(100) DEFAULT NULL,
  pincode             VARCHAR(10)  DEFAULT NULL,
  photo               VARCHAR(500) DEFAULT NULL,
  signature_path      VARCHAR(500) DEFAULT NULL,
  pan_number          VARCHAR(20)  DEFAULT NULL,
  aadhaar_number      VARCHAR(20)  DEFAULT NULL,
  bank_name           VARCHAR(200) DEFAULT NULL,
  bank_account_number VARCHAR(50)  DEFAULT NULL,
  ifsc_code           VARCHAR(20)  DEFAULT NULL,
  date_of_joining     DATE DEFAULT NULL,
  assigned_employer_id BIGINT UNSIGNED DEFAULT NULL,
  max_concurrent_audits INT NOT NULL DEFAULT 5,
  status              ENUM('active','inactive') NOT NULL DEFAULT 'active',
  username            VARCHAR(100) DEFAULT NULL,
  password_hash       VARCHAR(255) DEFAULT NULL,
  is_first_login      BOOLEAN NOT NULL DEFAULT TRUE,
  rating              DECIMAL(3,2) DEFAULT NULL,
  created_at          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by          BIGINT UNSIGNED DEFAULT NULL,
  updated_by          BIGINT UNSIGNED DEFAULT NULL,
  deleted_at          DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_aud_uuid (uuid),
  UNIQUE KEY uq_aud_code (auditor_code),
  UNIQUE KEY uq_aud_username (username),
  KEY idx_aud_name (name),
  KEY idx_aud_email (email),
  KEY idx_aud_mobile (mobile),
  KEY idx_aud_type (auditor_type_id),
  KEY idx_aud_status (status),
  KEY idx_aud_employer (assigned_employer_id),
  KEY idx_aud_deleted_at (deleted_at),
  CONSTRAINT fk_aud_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_aud_type FOREIGN KEY (auditor_type_id) REFERENCES auditor_types(id) ON DELETE SET NULL,
  CONSTRAINT fk_aud_employer FOREIGN KEY (assigned_employer_id) REFERENCES employers(id) ON DELETE SET NULL,
  CONSTRAINT fk_aud_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_aud_updated_by FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
