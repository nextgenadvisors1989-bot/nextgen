CREATE TABLE IF NOT EXISTS work_permits (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid              VARCHAR(36) NOT NULL,
  permit_number     VARCHAR(50) NOT NULL,
  permit_type       ENUM('Hot Work','Cold Work','Confined Space','Height Work','Electrical','Excavation',
                         'Lifting','Radiation','Chemical','General') NOT NULL,
  employer_id       BIGINT UNSIGNED NOT NULL,
  unit_id           BIGINT UNSIGNED DEFAULT NULL,
  department_id     BIGINT UNSIGNED DEFAULT NULL,
  work_description  TEXT NOT NULL,
  location_of_work  VARCHAR(255) DEFAULT NULL,
  contractor_name   VARCHAR(200) DEFAULT NULL,
  contractor_contact VARCHAR(20) DEFAULT NULL,
  workers_count     INT DEFAULT NULL,
  requested_by      VARCHAR(200) DEFAULT NULL,
  issued_by         VARCHAR(200) DEFAULT NULL,
  approved_by       BIGINT UNSIGNED DEFAULT NULL,
  valid_from        DATETIME DEFAULT NULL,
  valid_to          DATETIME DEFAULT NULL,
  safety_measures   TEXT,
  ppe_required      VARCHAR(500) DEFAULT NULL,
  ppe_provided      BOOLEAN NOT NULL DEFAULT FALSE,
  gas_test_required BOOLEAN NOT NULL DEFAULT FALSE,
  gas_test_result   VARCHAR(200) DEFAULT NULL,
  gas_tested_by     VARCHAR(200) DEFAULT NULL,
  gas_tested_at     DATETIME DEFAULT NULL,
  fire_watch_required BOOLEAN NOT NULL DEFAULT FALSE,
  fire_watch_details VARCHAR(255) DEFAULT NULL,
  status            ENUM('Draft','Pending Approval','Approved','Rejected','In Progress','Completed','Closed','Expired','Cancelled')
                    NOT NULL DEFAULT 'Draft',
  closure_remarks   TEXT,
  closed_at         DATETIME DEFAULT NULL,
  closed_by         BIGINT UNSIGNED DEFAULT NULL,
  auditor_id        BIGINT UNSIGNED DEFAULT NULL,
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by        BIGINT UNSIGNED DEFAULT NULL,
  updated_by        BIGINT UNSIGNED DEFAULT NULL,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_wp_uuid (uuid),
  UNIQUE KEY uq_wp_number (permit_number),
  KEY idx_wp_employer (employer_id),
  KEY idx_wp_type (permit_type),
  KEY idx_wp_status (status),
  KEY idx_wp_valid_to (valid_to),
  CONSTRAINT fk_wp_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_wp_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_wp_dept FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
  CONSTRAINT fk_wp_approved_by FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_wp_auditor FOREIGN KEY (auditor_id) REFERENCES auditors(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
