SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS assessment_reports (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid              VARCHAR(36) NOT NULL,
  assessment_number VARCHAR(50) NOT NULL,
  title             VARCHAR(255) NOT NULL,
  assessment_type   ENUM('HIRA','JSA','JHA','ENVIRONMENTAL','OCCUPATIONAL_HEALTH','FIRE','ERGONOMIC','OTHER')
                    NOT NULL DEFAULT 'HIRA',
  employer_id       BIGINT UNSIGNED NOT NULL,
  unit_id           BIGINT UNSIGNED DEFAULT NULL,
  department_id     BIGINT UNSIGNED DEFAULT NULL,
  activity          VARCHAR(500) DEFAULT NULL,
  process_area      VARCHAR(255) DEFAULT NULL,
  hazard_description TEXT,
  risk_category     ENUM('Physical','Chemical','Biological','Ergonomic','Mechanical','Electrical','Fire','Psychological','Other') DEFAULT NULL,
  likelihood        TINYINT DEFAULT NULL COMMENT '1-5',
  severity          TINYINT DEFAULT NULL COMMENT '1-5',
  risk_score        TINYINT DEFAULT NULL COMMENT 'likelihood x severity',
  risk_level        ENUM('Low','Medium','High','Extreme') DEFAULT NULL,
  existing_controls TEXT,
  additional_controls TEXT,
  residual_risk_score TINYINT DEFAULT NULL,
  residual_risk_level ENUM('Low','Medium','High','Extreme') DEFAULT NULL,
  responsible_person VARCHAR(200) DEFAULT NULL,
  target_date       DATE DEFAULT NULL,
  status            ENUM('Draft','Submitted','Under Review','Approved','Rejected','Changes Requested','Closed')
                    NOT NULL DEFAULT 'Draft',
  auditor_id        BIGINT UNSIGNED DEFAULT NULL,
  assignment_id     BIGINT UNSIGNED DEFAULT NULL,
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by        BIGINT UNSIGNED DEFAULT NULL,
  updated_by        BIGINT UNSIGNED DEFAULT NULL,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_asr_uuid (uuid),
  UNIQUE KEY uq_asr_number (assessment_number),
  KEY idx_asr_employer (employer_id),
  KEY idx_asr_status (status),
  KEY idx_asr_level (risk_level),
  CONSTRAINT fk_asr_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_asr_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_asr_auditor FOREIGN KEY (auditor_id) REFERENCES auditors(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS risk_reports (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid            VARCHAR(36) NOT NULL,
  risk_number     VARCHAR(50) NOT NULL,
  title           VARCHAR(255) NOT NULL,
  employer_id     BIGINT UNSIGNED NOT NULL,
  unit_id         BIGINT UNSIGNED DEFAULT NULL,
  department_id   BIGINT UNSIGNED DEFAULT NULL,
  hazard_id       VARCHAR(50) DEFAULT NULL,
  hazard_type     VARCHAR(150) DEFAULT NULL,
  risk_description TEXT,
  affected_persons VARCHAR(255) DEFAULT NULL,
  likelihood      TINYINT DEFAULT NULL,
  severity        TINYINT DEFAULT NULL,
  risk_score      TINYINT DEFAULT NULL,
  risk_level      ENUM('Low','Medium','High','Extreme') DEFAULT NULL,
  mitigation_plan TEXT,
  control_hierarchy ENUM('Elimination','Substitution','Engineering','Administrative','PPE') DEFAULT NULL,
  owner_name      VARCHAR(200) DEFAULT NULL,
  review_frequency ENUM('Monthly','Quarterly','Half-Yearly','Annual') DEFAULT NULL,
  next_review_date DATE DEFAULT NULL,
  status          ENUM('Open','In Progress','Mitigated','Accepted','Closed') NOT NULL DEFAULT 'Open',
  auditor_id      BIGINT UNSIGNED DEFAULT NULL,
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by      BIGINT UNSIGNED DEFAULT NULL,
  updated_by      BIGINT UNSIGNED DEFAULT NULL,
  deleted_at      DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rr_uuid (uuid),
  UNIQUE KEY uq_rr_number (risk_number),
  KEY idx_rr_employer (employer_id),
  KEY idx_rr_status (status),
  KEY idx_rr_level (risk_level),
  CONSTRAINT fk_rr_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_rr_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_rr_auditor FOREIGN KEY (auditor_id) REFERENCES auditors(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

