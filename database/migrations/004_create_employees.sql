  date_of_birth     DATE DEFAULT NULL,
  address           TEXT,
  share_percentage  DECIMAL(5,2) DEFAULT NULL,
  is_minor          BOOLEAN NOT NULL DEFAULT FALSE,
  guardian_name     VARCHAR(200) DEFAULT NULL,
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by        BIGINT UNSIGNED DEFAULT NULL,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_enom_employee (employee_id),
  KEY idx_enom_form (form_type),
  CONSTRAINT fk_enom_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Interview assessment captured during hiring (feeds the employee PDF, page 7).
