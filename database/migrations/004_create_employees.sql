SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS employees (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid                        VARCHAR(36) NOT NULL,
  employer_id                 BIGINT UNSIGNED NOT NULL,
  unit_id                     BIGINT UNSIGNED DEFAULT NULL,
  department_id               BIGINT UNSIGNED DEFAULT NULL,
  employee_number             VARCHAR(50) NOT NULL,
  name                        VARCHAR(200) NOT NULL,
  father_name                 VARCHAR(200) DEFAULT NULL,
  mother_name                 VARCHAR(200) DEFAULT NULL,
  spouse_name                 VARCHAR(200) DEFAULT NULL,
  sex                         ENUM('Male','Female','Other') DEFAULT NULL,
  marital_status              ENUM('Single','Married','Divorced','Widowed') DEFAULT NULL,
  religion                    VARCHAR(100) DEFAULT NULL,
  mother_tongue               VARCHAR(100) DEFAULT NULL,
  blood_group                 VARCHAR(10)  DEFAULT NULL,
  date_of_birth               DATE DEFAULT NULL,
  languages_known             TEXT,
  photo                       VARCHAR(500) DEFAULT NULL,
  aadhaar_number              VARCHAR(20) DEFAULT NULL,
  pan_number                  VARCHAR(20) DEFAULT NULL,
  present_address             TEXT,
  permanent_address           TEXT,
  is_permanent_same_as_present BOOLEAN NOT NULL DEFAULT FALSE,
  state                       VARCHAR(100) DEFAULT NULL,
  pincode                     VARCHAR(10)  DEFAULT NULL,
  telephone                   VARCHAR(20)  DEFAULT NULL,
  mobile                      VARCHAR(20)  DEFAULT NULL,
  email                       VARCHAR(255) DEFAULT NULL,
  native_place                VARCHAR(200) DEFAULT NULL,
  staying_in                  ENUM('Own','Rented') DEFAULT NULL,
  family_income_per_annum     DECIMAL(15,2) DEFAULT NULL,
  date_of_joining             DATE DEFAULT NULL,
  date_of_confirmation        DATE DEFAULT NULL,
  post_applied_for            VARCHAR(100) DEFAULT NULL,
  department                  VARCHAR(100) DEFAULT NULL,
  nature_of_work              VARCHAR(100) DEFAULT NULL,
  designation                 VARCHAR(100) DEFAULT NULL,
  category                    ENUM('Worker','Staff') DEFAULT NULL,
  grade                       VARCHAR(50) DEFAULT NULL,
  skill_grade                 VARCHAR(50) DEFAULT NULL,
  place_of_work               VARCHAR(200) DEFAULT NULL,
  shift_relay                 VARCHAR(50)  DEFAULT NULL,
  working_hours_from          TIME DEFAULT NULL,
  working_hours_to            TIME DEFAULT NULL,
  interval_lunch_time         TIME DEFAULT NULL,
  tea_break                   TIME DEFAULT NULL,
  weekly_off                  VARCHAR(50) DEFAULT NULL,
  probation_months            INT NOT NULL DEFAULT 3,
  basic_salary                DECIMAL(15,2) DEFAULT NULL,
  da                          DECIMAL(15,2) DEFAULT NULL,
  hra                         DECIMAL(15,2) DEFAULT NULL,
  ta                          DECIMAL(15,2) DEFAULT NULL,
  pa                          DECIMAL(15,2) DEFAULT NULL,
  ea                          DECIMAL(15,2) DEFAULT NULL,
  npba                        DECIMAL(15,2) DEFAULT NULL,
  other_allowances            DECIMAL(15,2) DEFAULT NULL,
  gross_salary                DECIMAL(15,2) DEFAULT NULL,
  wage_type                   ENUM('Per Day','Per Month') DEFAULT NULL,
  expected_salary             DECIMAL(15,2) DEFAULT NULL,
  pf_number                   VARCHAR(50) DEFAULT NULL,
  pf_effective_date           DATE DEFAULT NULL,
  uan                         VARCHAR(50) DEFAULT NULL,
  esi_number                  VARCHAR(50) DEFAULT NULL,
  esi_dispensary              VARCHAR(200) DEFAULT NULL,
  mediclaim_number            VARCHAR(50) DEFAULT NULL,
  previous_pf_account_number  VARCHAR(50) DEFAULT NULL,
  previous_employer_exit_date DATE DEFAULT NULL,
  scheme_certificate_number   VARCHAR(50) DEFAULT NULL,
  pension_payment_order_number VARCHAR(50) DEFAULT NULL,
  is_international_worker     BOOLEAN NOT NULL DEFAULT FALSE,
  country                     VARCHAR(100) DEFAULT NULL,
  passport_number             VARCHAR(50) DEFAULT NULL,
  passport_validity           DATE DEFAULT NULL,
  bank_name                   VARCHAR(200) DEFAULT NULL,
  bank_account_number         VARCHAR(50) DEFAULT NULL,
  ifsc_code                   VARCHAR(20) DEFAULT NULL,
  user_id                     BIGINT UNSIGNED DEFAULT NULL,
  username                    VARCHAR(100) DEFAULT NULL,
  password_hash               VARCHAR(255) DEFAULT NULL,
  is_first_login              BOOLEAN NOT NULL DEFAULT TRUE,
  status                      ENUM('active','inactive','terminated','resigned') NOT NULL DEFAULT 'active',
  date_of_resignation         DATE DEFAULT NULL,
  date_of_relieving           DATE DEFAULT NULL,
  resignation_reason          TEXT,
  is_re_employment_eligible   BOOLEAN NOT NULL DEFAULT TRUE,
  re_employment_remarks       TEXT,
  created_at                  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by                  BIGINT UNSIGNED DEFAULT NULL,
  updated_by                  BIGINT UNSIGNED DEFAULT NULL,
  deleted_at                  DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_emp_uuid (uuid),
  UNIQUE KEY uq_emp_number (employee_number),
  UNIQUE KEY uq_emp_username (username),
  UNIQUE KEY uq_emp_aadhaar (aadhaar_number),
  KEY idx_emp_employer (employer_id),
  KEY idx_emp_unit (unit_id),
  KEY idx_emp_department (department_id),
  KEY idx_emp_name (name),
  KEY idx_emp_mobile (mobile),
  KEY idx_emp_email (email),
  KEY idx_emp_doj (date_of_joining),
  KEY idx_emp_dob (date_of_birth),
  KEY idx_emp_designation (designation),
  KEY idx_emp_status (status),
  KEY idx_emp_deleted_at (deleted_at),
  CONSTRAINT fk_emp_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_emp_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_emp_department FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
  CONSTRAINT fk_emp_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_emp_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_emp_updated_by FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS employee_documents (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  employee_id   BIGINT UNSIGNED NOT NULL,
  document_type VARCHAR(100) NOT NULL,
  document_name VARCHAR(255) NOT NULL,
  file_id       BIGINT UNSIGNED DEFAULT NULL,
  file_path     VARCHAR(500) DEFAULT NULL,
  file_size     BIGINT UNSIGNED DEFAULT NULL,
  mime_type     VARCHAR(150) DEFAULT NULL,
  issue_date    DATE DEFAULT NULL,
  expiry_date   DATE DEFAULT NULL,
  document_number VARCHAR(100) DEFAULT NULL,
  is_verified   BOOLEAN NOT NULL DEFAULT FALSE,
  verified_by   BIGINT UNSIGNED DEFAULT NULL,
  verified_at   DATETIME DEFAULT NULL,
  remarks       TEXT,
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by    BIGINT UNSIGNED DEFAULT NULL,
  deleted_at    DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_edoc_employee (employee_id),
  KEY idx_edoc_type (document_type),
  KEY idx_edoc_expiry (expiry_date),
  CONSTRAINT fk_edoc_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
  CONSTRAINT fk_edoc_verified_by FOREIGN KEY (verified_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS employee_service_records (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
