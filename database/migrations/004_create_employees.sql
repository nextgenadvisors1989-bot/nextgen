-- 16-item personal file checklist; the canonical item list is seeded in the
-- personal_file_checklist_items table, per-employee state lives here.
CREATE TABLE IF NOT EXISTS personal_file_checklist_items (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  item_code   VARCHAR(50) NOT NULL,
  item_label  VARCHAR(255) NOT NULL,
  sort_order  INT NOT NULL DEFAULT 0,
  is_mandatory BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_pfci_code (item_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS employee_file_checklist (
  id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  employee_id  BIGINT UNSIGNED NOT NULL,
  item_id      BIGINT UNSIGNED NOT NULL,
  is_checked   BOOLEAN NOT NULL DEFAULT FALSE,
  checked_by   BIGINT UNSIGNED DEFAULT NULL,
  checked_at   DATETIME DEFAULT NULL,
  remarks      VARCHAR(500) DEFAULT NULL,
  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_efc (employee_id, item_id),
  CONSTRAINT fk_efc_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
  CONSTRAINT fk_efc_item FOREIGN KEY (item_id) REFERENCES personal_file_checklist_items(id) ON DELETE CASCADE,
  CONSTRAINT fk_efc_checked_by FOREIGN KEY (checked_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
