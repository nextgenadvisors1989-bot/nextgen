-- 008_create_dynamic_form_submissions.sql — submitted form instances and their values
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS dynamic_form_submissions (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid              VARCHAR(36) NOT NULL,
  submission_number VARCHAR(50) NOT NULL,
  module_id         BIGINT UNSIGNED NOT NULL,
  form_id           BIGINT UNSIGNED NOT NULL,
  assignment_id     BIGINT UNSIGNED DEFAULT NULL,
  employer_id       BIGINT UNSIGNED DEFAULT NULL,
  unit_id           BIGINT UNSIGNED DEFAULT NULL,
  department_id     BIGINT UNSIGNED DEFAULT NULL,
  submitted_by      BIGINT UNSIGNED DEFAULT NULL COMMENT 'users.id of the auditor/creator',
  auditor_id        BIGINT UNSIGNED DEFAULT NULL,
  title             VARCHAR(255) DEFAULT NULL,
  status            ENUM('draft','submitted','under_review','approved','rejected','changes_requested','archived')
                    NOT NULL DEFAULT 'draft',
  score_obtained    DECIMAL(10,2) DEFAULT NULL,
  score_max         DECIMAL(10,2) DEFAULT NULL,
  score_percentage  DECIMAL(6,2) DEFAULT NULL,
  submission_date   DATETIME DEFAULT NULL,
  period_from       DATE DEFAULT NULL,
  period_to         DATE DEFAULT NULL,
  remarks           TEXT,
  pdf_file_id       BIGINT UNSIGNED DEFAULT NULL,
  pdf_generated_at  DATETIME DEFAULT NULL,
  version           INT NOT NULL DEFAULT 1,
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by        BIGINT UNSIGNED DEFAULT NULL,
  updated_by        BIGINT UNSIGNED DEFAULT NULL,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_dfs_uuid (uuid),
  UNIQUE KEY uq_dfs_number (submission_number),
  KEY idx_dsub_module (module_id),
  KEY idx_dsub_form (form_id),
  KEY idx_dsub_assignment (assignment_id),
  KEY idx_dsub_employer (employer_id),
  KEY idx_dsub_status (status),
  KEY idx_dsub_date (submission_date),
  KEY idx_dsub_creator (created_by),
  CONSTRAINT fk_dsub_module FOREIGN KEY (module_id) REFERENCES dynamic_modules(id) ON DELETE CASCADE,
  CONSTRAINT fk_dsub_form FOREIGN KEY (form_id) REFERENCES dynamic_forms(id) ON DELETE CASCADE,
  CONSTRAINT fk_dsub_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_dsub_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_dsub_dept FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
  CONSTRAINT fk_dsub_submitted_by FOREIGN KEY (submitted_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_dsub_auditor FOREIGN KEY (auditor_id) REFERENCES auditors(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dynamic_form_submission_values (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  submission_id BIGINT UNSIGNED NOT NULL,
  form_id       BIGINT UNSIGNED NOT NULL,
  section_id    BIGINT UNSIGNED DEFAULT NULL,
  field_id      BIGINT UNSIGNED NOT NULL,
  field_key     VARCHAR(100) NOT NULL,
  value_text    LONGTEXT,
  value_number  DECIMAL(18,4) DEFAULT NULL,
  value_date    DATE DEFAULT NULL,
  value_datetime DATETIME DEFAULT NULL,
  value_json    JSON DEFAULT NULL,
  file_id       BIGINT UNSIGNED DEFAULT NULL,
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_dfsv (submission_id, field_id),
  KEY idx_dfsv_submission (submission_id),
  KEY idx_dfsv_field (field_id),
  KEY idx_dfsv_key (field_key),
  CONSTRAINT fk_dfsv_submission FOREIGN KEY (submission_id) REFERENCES dynamic_form_submissions(id) ON DELETE CASCADE,
  CONSTRAINT fk_dfsv_form FOREIGN KEY (form_id) REFERENCES dynamic_forms(id) ON DELETE CASCADE,
  CONSTRAINT fk_dfsv_field FOREIGN KEY (field_id) REFERENCES dynamic_form_fields(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dynamic_table_rows (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  submission_id BIGINT UNSIGNED NOT NULL,
  table_id      BIGINT UNSIGNED NOT NULL,
  row_index     INT NOT NULL DEFAULT 0,
  row_data      JSON NOT NULL COMMENT 'column_key -> value map',
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_dtr_submission (submission_id),
  KEY idx_dtr_table (table_id),
  UNIQUE KEY uq_dtr_row (submission_id, table_id, row_index),
  CONSTRAINT fk_dtr_submission FOREIGN KEY (submission_id) REFERENCES dynamic_form_submissions(id) ON DELETE CASCADE,
  CONSTRAINT fk_dtr_table FOREIGN KEY (table_id) REFERENCES dynamic_tables(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
