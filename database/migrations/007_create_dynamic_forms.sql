-- 007_create_dynamic_forms.sql — forms, sections, fields, options, repeatable tables
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS dynamic_forms (
  id                    BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  module_id             BIGINT UNSIGNED NOT NULL,
  name                  VARCHAR(200) NOT NULL,
  slug                  VARCHAR(200) NOT NULL,
  description           TEXT,
  form_type             ENUM('STANDARD','AUDIT','CHECKLIST','INSPECTION','PERMIT','ASSESSMENT') NOT NULL DEFAULT 'STANDARD',
  version               INT NOT NULL DEFAULT 1,
  layout_columns        TINYINT NOT NULL DEFAULT 2,
  requires_signature    BOOLEAN NOT NULL DEFAULT TRUE,
  requires_attachments  BOOLEAN NOT NULL DEFAULT FALSE,
  allow_draft           BOOLEAN NOT NULL DEFAULT TRUE,
  auto_number_prefix    VARCHAR(20) DEFAULT NULL,
  pdf_template_id       BIGINT UNSIGNED DEFAULT NULL,
  status                ENUM('draft','published','archived') NOT NULL DEFAULT 'draft',
  created_at            DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at            DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by            BIGINT UNSIGNED DEFAULT NULL,
  updated_by            BIGINT UNSIGNED DEFAULT NULL,
  deleted_at            DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_df_slug (module_id, slug),
  KEY idx_df_module (module_id),
  KEY idx_df_status (status),
  CONSTRAINT fk_df_module FOREIGN KEY (module_id) REFERENCES dynamic_modules(id) ON DELETE CASCADE,
  CONSTRAINT fk_df_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_df_updated_by FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dynamic_form_sections (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  form_id        BIGINT UNSIGNED NOT NULL,
  title          VARCHAR(255) NOT NULL,
  section_code   VARCHAR(100) DEFAULT NULL,
  description    TEXT,
  layout_columns TINYINT NOT NULL DEFAULT 2,
  is_repeatable  BOOLEAN NOT NULL DEFAULT FALSE,
  is_collapsible BOOLEAN NOT NULL DEFAULT TRUE,
  is_collapsed   BOOLEAN NOT NULL DEFAULT FALSE,
  show_in_pdf    BOOLEAN NOT NULL DEFAULT TRUE,
  page_break_before BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order     INT NOT NULL DEFAULT 0,
  status         ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by     BIGINT UNSIGNED DEFAULT NULL,
  deleted_at     DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_dfs_form (form_id),
  KEY idx_dfs_sort (form_id, sort_order),
  CONSTRAINT fk_dfs_form FOREIGN KEY (form_id) REFERENCES dynamic_forms(id) ON DELETE CASCADE,
  CONSTRAINT fk_dfs_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dynamic_form_fields (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  form_id           BIGINT UNSIGNED NOT NULL,
  section_id        BIGINT UNSIGNED NOT NULL,
  field_key         VARCHAR(100) NOT NULL,
  label             VARCHAR(255) NOT NULL,
  label_ta          VARCHAR(255) DEFAULT NULL COMMENT 'Tamil label for bilingual PDF',
  field_type        ENUM('text','textarea','rich_text','number','decimal','currency','date','time','datetime',
                         'email','phone','url','password','select','multi_select','radio','checkbox','switch',
                         'file','multi_file','image','signature','rating','table','heading','paragraph',
                         'divider','formula','auto_number') NOT NULL,
  placeholder       VARCHAR(255) DEFAULT NULL,
  help_text         VARCHAR(500) DEFAULT NULL,
  default_value     TEXT,
  options_json      JSON DEFAULT NULL,
  validation_json   JSON DEFAULT NULL,
  conditional_json  JSON DEFAULT NULL,
  table_definition_id BIGINT UNSIGNED DEFAULT NULL,
  formula_expression VARCHAR(500) DEFAULT NULL,
  is_required       BOOLEAN NOT NULL DEFAULT FALSE,
  is_readonly       BOOLEAN NOT NULL DEFAULT FALSE,
  is_unique         BOOLEAN NOT NULL DEFAULT FALSE,
  show_in_pdf       BOOLEAN NOT NULL DEFAULT TRUE,
  show_in_list      BOOLEAN NOT NULL DEFAULT FALSE,
  column_width      TINYINT NOT NULL DEFAULT 6 COMMENT '1-12 grid columns',
  min_value         DECIMAL(18,4) DEFAULT NULL,
  max_value         DECIMAL(18,4) DEFAULT NULL,
  min_length        INT DEFAULT NULL,
  max_length        INT DEFAULT NULL,
  regex_pattern     VARCHAR(500) DEFAULT NULL,
  sort_order        INT NOT NULL DEFAULT 0,
  status            ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by        BIGINT UNSIGNED DEFAULT NULL,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_dff_key (form_id, field_key),
  KEY idx_dff_form (form_id),
  KEY idx_dff_section (section_id),
  KEY idx_dff_sort (section_id, sort_order),
  KEY idx_dff_type (field_type),
  CONSTRAINT fk_dff_form FOREIGN KEY (form_id) REFERENCES dynamic_forms(id) ON DELETE CASCADE,
  CONSTRAINT fk_dff_section FOREIGN KEY (section_id) REFERENCES dynamic_form_sections(id) ON DELETE CASCADE,
  CONSTRAINT fk_dff_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dynamic_field_options (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  field_id    BIGINT UNSIGNED NOT NULL,
  option_key  VARCHAR(100) NOT NULL,
  option_label VARCHAR(255) NOT NULL,
  option_label_ta VARCHAR(255) DEFAULT NULL,
  option_value VARCHAR(255) DEFAULT NULL,
  color       VARCHAR(20) DEFAULT NULL,
  score       DECIMAL(10,2) DEFAULT NULL COMMENT 'Used for scored checklists (Yes/No/NA weighting)',
  is_default  BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order  INT NOT NULL DEFAULT 0,
  status      ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_dfo_key (field_id, option_key),
  KEY idx_dfo_field (field_id),
  CONSTRAINT fk_dfo_field FOREIGN KEY (field_id) REFERENCES dynamic_form_fields(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dynamic_tables (
  id               BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  form_id          BIGINT UNSIGNED NOT NULL,
  section_id       BIGINT UNSIGNED DEFAULT NULL,
  table_key        VARCHAR(100) NOT NULL,
  table_name       VARCHAR(200) NOT NULL,
  table_name_ta    VARCHAR(200) DEFAULT NULL,
  description      TEXT,
  is_repeatable    BOOLEAN NOT NULL DEFAULT TRUE,
  min_rows         INT NOT NULL DEFAULT 0,
  max_rows         INT DEFAULT NULL,
  show_row_numbers BOOLEAN NOT NULL DEFAULT TRUE,
  show_totals      BOOLEAN NOT NULL DEFAULT FALSE,
  show_in_pdf      BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order       INT NOT NULL DEFAULT 0,
  status           ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by       BIGINT UNSIGNED DEFAULT NULL,
  deleted_at       DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_dt_key (form_id, table_key),
  KEY idx_dt_form (form_id),
  CONSTRAINT fk_dt_form FOREIGN KEY (form_id) REFERENCES dynamic_forms(id) ON DELETE CASCADE,
  CONSTRAINT fk_dt_section FOREIGN KEY (section_id) REFERENCES dynamic_form_sections(id) ON DELETE CASCADE,
  CONSTRAINT fk_dt_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dynamic_table_columns (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  table_id      BIGINT UNSIGNED NOT NULL,
  column_key    VARCHAR(100) NOT NULL,
  column_label  VARCHAR(255) NOT NULL,
  column_label_ta VARCHAR(255) DEFAULT NULL,
  column_type   ENUM('text','textarea','number','decimal','currency','date','time','select','multi_select',
                     'checkbox','file','formula','auto_number') NOT NULL DEFAULT 'text',
  options_json  JSON DEFAULT NULL,
  formula_expression VARCHAR(500) DEFAULT NULL,
  default_value TEXT,
  width_pct     DECIMAL(5,2) DEFAULT NULL,
  is_required   BOOLEAN NOT NULL DEFAULT FALSE,
  is_editable   BOOLEAN NOT NULL DEFAULT TRUE,
  is_sortable   BOOLEAN NOT NULL DEFAULT FALSE,
  is_total      BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Sum this column when show_totals=1',
  show_in_pdf   BOOLEAN NOT NULL DEFAULT TRUE,
  validation_json JSON DEFAULT NULL,
  sort_order    INT NOT NULL DEFAULT 0,
  status        ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by    BIGINT UNSIGNED DEFAULT NULL,
  deleted_at    DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_dtc_key (table_id, column_key),
  KEY idx_dtc_table (table_id),
  KEY idx_dtc_sort (table_id, sort_order),
  CONSTRAINT fk_dtc_table FOREIGN KEY (table_id) REFERENCES dynamic_tables(id) ON DELETE CASCADE,
  CONSTRAINT fk_dtc_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

