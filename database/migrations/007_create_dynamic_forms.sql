  footer_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  footer_html    TEXT,
  show_page_numbers BOOLEAN NOT NULL DEFAULT TRUE,
  show_company_header BOOLEAN NOT NULL DEFAULT TRUE,
  repeat_table_headers BOOLEAN NOT NULL DEFAULT TRUE,
  watermark_text VARCHAR(100) DEFAULT NULL,
  sections_json  JSON DEFAULT NULL COMMENT 'Ordered section/field visibility for the PDF',
  is_default     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by     BIGINT UNSIGNED DEFAULT NULL,
  deleted_at     DATETIME DEFAULT NULL,
