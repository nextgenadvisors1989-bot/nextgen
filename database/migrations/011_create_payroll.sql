CREATE TABLE IF NOT EXISTS payroll_heads (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  head_code     VARCHAR(30) NOT NULL,
  head_name     VARCHAR(150) NOT NULL,
  head_name_ta  VARCHAR(150) DEFAULT NULL COMMENT 'Tamil label for bilingual payslip',
  head_type     ENUM('Earning','Deduction','Employer Contribution') NOT NULL,
  calculation_type ENUM('Fixed','Percent of Basic','Percent of Gross','Formula','Attendance Based') NOT NULL DEFAULT 'Fixed',
  percent_value DECIMAL(7,3) DEFAULT NULL,
  formula       VARCHAR(500) DEFAULT NULL,
  is_statutory  BOOLEAN NOT NULL DEFAULT FALSE,
  is_taxable    BOOLEAN NOT NULL DEFAULT TRUE,
  is_pf_applicable BOOLEAN NOT NULL DEFAULT FALSE,
  is_esi_applicable BOOLEAN NOT NULL DEFAULT FALSE,
  show_on_payslip BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order    INT NOT NULL DEFAULT 0,
  status        ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ph_code (head_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS attendance (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  employer_id     BIGINT UNSIGNED NOT NULL,
  unit_id         BIGINT UNSIGNED DEFAULT NULL,
  department_id   BIGINT UNSIGNED DEFAULT NULL,
  employee_id     BIGINT UNSIGNED NOT NULL,
  attendance_date DATE NOT NULL,
  month           TINYINT UNSIGNED NOT NULL,
  year            SMALLINT UNSIGNED NOT NULL,
  status          ENUM('Present','Absent','Half Day','Leave','Holiday','Weekly Off','On Duty','Late','Comp Off')
                  NOT NULL DEFAULT 'Present',
  leave_type      VARCHAR(50) DEFAULT NULL,
  shift_name      VARCHAR(50) DEFAULT NULL,
  in_time         TIME DEFAULT NULL,
  out_time        TIME DEFAULT NULL,
  worked_hours    DECIMAL(5,2) DEFAULT NULL,
  overtime_hours  DECIMAL(5,2) NOT NULL DEFAULT 0,
  late_minutes    INT NOT NULL DEFAULT 0,
  early_minutes   INT NOT NULL DEFAULT 0,
  is_paid         BOOLEAN NOT NULL DEFAULT TRUE,
  remarks         VARCHAR(500) DEFAULT NULL,
  source          ENUM('Manual','Bulk Upload','Biometric','Import') NOT NULL DEFAULT 'Manual',
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by      BIGINT UNSIGNED DEFAULT NULL,
  updated_by      BIGINT UNSIGNED DEFAULT NULL,
  deleted_at      DATETIME DEFAULT NULL,
