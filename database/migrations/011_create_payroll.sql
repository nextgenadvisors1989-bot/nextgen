  UNIQUE KEY uq_att_emp_date (employee_id, attendance_date),
  KEY idx_att_employer_month (employer_id, year, month),
  KEY idx_att_date (attendance_date),
  KEY idx_att_status (status),
  KEY idx_att_dept (department_id),
  CONSTRAINT fk_att_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_att_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_att_dept FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
