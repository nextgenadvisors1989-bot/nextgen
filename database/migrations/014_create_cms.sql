-- 014_create_cms.sql — public website content, media library, downloadable resources
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS cms_pages (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid            VARCHAR(36) NOT NULL,
  slug            VARCHAR(255) NOT NULL,
  title           VARCHAR(255) NOT NULL,
  subtitle        VARCHAR(500) DEFAULT NULL,
  meta_title      VARCHAR(255) DEFAULT NULL,
  meta_description VARCHAR(500) DEFAULT NULL,
  meta_keywords   VARCHAR(500) DEFAULT NULL,
  hero_image      VARCHAR(500) DEFAULT NULL,
  content_html    LONGTEXT,
  content_json    JSON DEFAULT NULL COMMENT 'Structured block content for the editor',
  page_type       ENUM('page','blog','faq','legal','landing') NOT NULL DEFAULT 'page',
  template        VARCHAR(100) NOT NULL DEFAULT 'default',
  parent_page_id  BIGINT UNSIGNED DEFAULT NULL,
  sort_order      INT NOT NULL DEFAULT 0,
  show_in_menu    BOOLEAN NOT NULL DEFAULT FALSE,
  menu_label      VARCHAR(100) DEFAULT NULL,
  status          ENUM('draft','published','archived','scheduled') NOT NULL DEFAULT 'draft',
  is_homepage     BOOLEAN NOT NULL DEFAULT FALSE,
  published_at    DATETIME DEFAULT NULL,
  scheduled_at    DATETIME DEFAULT NULL,
  view_count      INT NOT NULL DEFAULT 0,
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by      BIGINT UNSIGNED DEFAULT NULL,
  updated_by      BIGINT UNSIGNED DEFAULT NULL,
  deleted_at      DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_cp_uuid (uuid),
  UNIQUE KEY uq_cp_slug (slug),
  KEY idx_cp_status (status),
  KEY idx_cp_type (page_type),
  KEY idx_cp_menu (show_in_menu),
  CONSTRAINT fk_cp_parent FOREIGN KEY (parent_page_id) REFERENCES cms_pages(id) ON DELETE SET NULL,
  CONSTRAINT fk_cp_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cms_page_sections (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  page_id     BIGINT UNSIGNED NOT NULL,
  section_key VARCHAR(100) DEFAULT NULL,
  section_type ENUM('hero','text','richtext','features','stats','cta','accordion','tabs','table',
                    'image','gallery','team','testimonials','pricing','contact_form','faq','services','custom')
               NOT NULL DEFAULT 'text',
  heading     VARCHAR(255) DEFAULT NULL,
  subheading  VARCHAR(500) DEFAULT NULL,
  content_html LONGTEXT,
  content_json JSON DEFAULT NULL,
  image_url   VARCHAR(500) DEFAULT NULL,
  background_color VARCHAR(20) DEFAULT NULL,
  sort_order  INT NOT NULL DEFAULT 0,
  status      ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by  BIGINT UNSIGNED DEFAULT NULL,
  deleted_at  DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_cps_page (page_id),
  CONSTRAINT fk_cps_page FOREIGN KEY (page_id) REFERENCES cms_pages(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cms_media (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid          VARCHAR(36) NOT NULL,
  file_id       BIGINT UNSIGNED DEFAULT NULL,
  title         VARCHAR(255) DEFAULT NULL,
  alt_text      VARCHAR(500) DEFAULT NULL,
  caption       VARCHAR(500) DEFAULT NULL,
  file_name     VARCHAR(500) NOT NULL,
  file_path     VARCHAR(1000) NOT NULL,
  public_url    VARCHAR(1000) DEFAULT NULL,
  mime_type     VARCHAR(150) DEFAULT NULL,
  media_type    ENUM('image','video','audio','document','other') NOT NULL DEFAULT 'image',
  size_bytes    BIGINT UNSIGNED NOT NULL DEFAULT 0,
  width         INT DEFAULT NULL,
  height        INT DEFAULT NULL,
  folder        VARCHAR(255) DEFAULT NULL,
  tags          VARCHAR(500) DEFAULT NULL,
  uploaded_by   BIGINT UNSIGNED DEFAULT NULL,
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at    DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_cm_uuid (uuid),
  KEY idx_cm_type (media_type),
  KEY idx_cm_folder (folder),
  CONSTRAINT fk_cm_file FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cms_resources (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid          VARCHAR(36) NOT NULL,
  title         VARCHAR(255) NOT NULL,
  slug          VARCHAR(255) NOT NULL,
  description   TEXT,
  resource_type ENUM('Guide','Checklist','Template','Circular','Act','Rule','Report','Whitepaper','Video','Other')
                NOT NULL DEFAULT 'Guide',
  category      VARCHAR(100) DEFAULT NULL,
  act_id        BIGINT UNSIGNED DEFAULT NULL,
  file_id       BIGINT UNSIGNED DEFAULT NULL,
  external_url  VARCHAR(1000) DEFAULT NULL,
  thumbnail     VARCHAR(500) DEFAULT NULL,
  requires_login BOOLEAN NOT NULL DEFAULT FALSE,
  download_count INT NOT NULL DEFAULT 0,
  sort_order    INT NOT NULL DEFAULT 0,
  status        ENUM('draft','published','archived') NOT NULL DEFAULT 'draft',
  published_at  DATETIME DEFAULT NULL,
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by    BIGINT UNSIGNED DEFAULT NULL,
  updated_by    BIGINT UNSIGNED DEFAULT NULL,
  deleted_at    DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_cres_uuid (uuid),
  UNIQUE KEY uq_cres_slug (slug),
  KEY idx_cres_type (resource_type),
  KEY idx_cres_status (status),
  CONSTRAINT fk_cres_act FOREIGN KEY (act_id) REFERENCES compliance_acts(id) ON DELETE SET NULL,
  CONSTRAINT fk_cres_file FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS contact_enquiries (
  id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name         VARCHAR(200) NOT NULL,
  email        VARCHAR(255) NOT NULL,
  mobile       VARCHAR(20) DEFAULT NULL,
  company_name VARCHAR(255) DEFAULT NULL,
  subject      VARCHAR(300) DEFAULT NULL,
  message      TEXT NOT NULL,
  enquiry_type ENUM('General','Demo Request','Sales','Support','Partnership','Careers') NOT NULL DEFAULT 'General',
  source_page  VARCHAR(255) DEFAULT NULL,
  status       ENUM('New','In Progress','Responded','Closed','Spam') NOT NULL DEFAULT 'New',
  assigned_to  BIGINT UNSIGNED DEFAULT NULL,
  response     TEXT,
  responded_at DATETIME DEFAULT NULL,
  ip_address   VARCHAR(45) DEFAULT NULL,
  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_ce_status (status),
  KEY idx_ce_created (created_at),
  CONSTRAINT fk_ce_assigned FOREIGN KEY (assigned_to) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
