-- 009_create_audit_management.sql — assignments, reports, versions, comments, verifier workflow
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS audit_assignments (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid              VARCHAR(36) NOT NULL,
  assignment_number VARCHAR(50) NOT NULL,
  assignment_type   ENUM('AUDIT','ASSESSMENT','RISK','STUDY','WORK_PERMIT','INSPECTION') NOT NULL DEFAULT 'AUDIT',
  audit_title       VARCHAR(255) NOT NULL,
  module_id         BIGINT UNSIGNED DEFAULT NULL,
  form_id           BIGINT UNSIGNED DEFAULT NULL,
  employer_id       BIGINT UNSIGNED NOT NULL,
  unit_id           BIGINT UNSIGNED DEFAULT NULL,
  department_id     BIGINT UNSIGNED DEFAULT NULL,
  auditor_id        BIGINT UNSIGNED NOT NULL,
  verifier_id       BIGINT UNSIGNED DEFAULT NULL,
  assigned_by       BIGINT UNSIGNED DEFAULT NULL,
  start_date        DATE DEFAULT NULL,
  end_date          DATE DEFAULT NULL,
  due_date          DATE DEFAULT NULL,
  completed_at      DATETIME DEFAULT NULL,
  audit_end_meeting_at DATETIME DEFAULT NULL,
  priority          ENUM('Low','Medium','High','Urgent') NOT NULL DEFAULT 'Medium',
  status            ENUM('Not Started','In Progress','Draft Saved','Submitted','Under Review',
                         'Approved','Rejected','Changes Requested','Overdue','Cancelled') NOT NULL DEFAULT 'Not Started',
  progress_percent  TINYINT UNSIGNED NOT NULL DEFAULT 0,
  instructions      TEXT,
  scope             TEXT,
  fee_amount        DECIMAL(15,2) DEFAULT NULL,
  revision_count    INT NOT NULL DEFAULT 0,
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by        BIGINT UNSIGNED DEFAULT NULL,
  updated_by        BIGINT UNSIGNED DEFAULT NULL,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_aa_uuid (uuid),
  UNIQUE KEY uq_aa_number (assignment_number),
  KEY idx_aa_employer (employer_id),
  KEY idx_aa_auditor (auditor_id),
  KEY idx_aa_verifier (verifier_id),
  KEY idx_aa_status (status),
  KEY idx_aa_priority (priority),
  KEY idx_aa_due (due_date),
  KEY idx_aa_start (start_date),
  KEY idx_aa_type (assignment_type),
  KEY idx_aa_deleted_at (deleted_at),
  CONSTRAINT fk_aa_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_aa_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_aa_dept FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
  CONSTRAINT fk_aa_auditor FOREIGN KEY (auditor_id) REFERENCES auditors(id) ON DELETE CASCADE,
  CONSTRAINT fk_aa_verifier FOREIGN KEY (verifier_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_aa_assigned_by FOREIGN KEY (assigned_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_aa_module FOREIGN KEY (module_id) REFERENCES dynamic_modules(id) ON DELETE SET NULL,
  CONSTRAINT fk_aa_form FOREIGN KEY (form_id) REFERENCES dynamic_forms(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS audit_reports (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid              VARCHAR(36) NOT NULL,
  report_number     VARCHAR(50) NOT NULL,
  assignment_id     BIGINT UNSIGNED DEFAULT NULL,
  submission_id     BIGINT UNSIGNED DEFAULT NULL,
  module_id         BIGINT UNSIGNED DEFAULT NULL,
  form_id           BIGINT UNSIGNED DEFAULT NULL,
  employer_id       BIGINT UNSIGNED NOT NULL,
  unit_id           BIGINT UNSIGNED DEFAULT NULL,
  auditor_id        BIGINT UNSIGNED DEFAULT NULL,
  audit_title       VARCHAR(255) NOT NULL,
  report_type       ENUM('AUDIT','ASSESSMENT','RISK','STUDY','WORK_PERMIT','INSPECTION') NOT NULL DEFAULT 'AUDIT',
  audit_period_from DATE DEFAULT NULL,
  audit_period_to   DATE DEFAULT NULL,
  audit_date        DATE DEFAULT NULL,
  status            ENUM('Draft','Submitted','Under Review','Approved','Rejected','Changes Requested','Archived')
                    NOT NULL DEFAULT 'Draft',
  current_version   INT NOT NULL DEFAULT 1,
  score_obtained    DECIMAL(10,2) DEFAULT NULL,
  score_max         DECIMAL(10,2) DEFAULT NULL,
  score_percentage  DECIMAL(6,2) DEFAULT NULL,
  critical_findings INT NOT NULL DEFAULT 0,
  major_findings    INT NOT NULL DEFAULT 0,
  minor_findings    INT NOT NULL DEFAULT 0,
  observations      INT NOT NULL DEFAULT 0,
  pdf_file_id       BIGINT UNSIGNED DEFAULT NULL,
  pdf_generated_at  DATETIME DEFAULT NULL,
  submitted_at      DATETIME DEFAULT NULL,
  approved_at       DATETIME DEFAULT NULL,
  approved_by       BIGINT UNSIGNED DEFAULT NULL,
  rejected_at       DATETIME DEFAULT NULL,
  rejected_by       BIGINT UNSIGNED DEFAULT NULL,
  rejection_reason  TEXT,
  next_audit_due    DATE DEFAULT NULL,
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by        BIGINT UNSIGNED DEFAULT NULL,
  updated_by        BIGINT UNSIGNED DEFAULT NULL,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ar_uuid (uuid),
  UNIQUE KEY uq_ar_number (report_number),
  KEY idx_ar_employer (employer_id),
  KEY idx_ar_auditor (auditor_id),
  KEY idx_ar_assignment (assignment_id),
  KEY idx_ar_status (status),
  KEY idx_ar_type (report_type),
  KEY idx_ar_submitted (submitted_at),
  KEY idx_ar_deleted_at (deleted_at),
  CONSTRAINT fk_ar_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_ar_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_ar_auditor FOREIGN KEY (auditor_id) REFERENCES auditors(id) ON DELETE SET NULL,
  CONSTRAINT fk_ar_assignment FOREIGN KEY (assignment_id) REFERENCES audit_assignments(id) ON DELETE SET NULL,
  CONSTRAINT fk_ar_submission FOREIGN KEY (submission_id) REFERENCES dynamic_form_submissions(id) ON DELETE SET NULL,
  CONSTRAINT fk_ar_module FOREIGN KEY (module_id) REFERENCES dynamic_modules(id) ON DELETE SET NULL,
  CONSTRAINT fk_ar_form FOREIGN KEY (form_id) REFERENCES dynamic_forms(id) ON DELETE SET NULL,
  CONSTRAINT fk_ar_approved_by FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_ar_rejected_by FOREIGN KEY (rejected_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Immutable snapshot of every submitted revision (audit trail for verifiers).
CREATE TABLE IF NOT EXISTS audit_report_versions (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  report_id     BIGINT UNSIGNED NOT NULL,
  version       INT NOT NULL,
  snapshot_json LONGTEXT NOT NULL COMMENT 'frozen JSON of report + form values + table rows',
  pdf_file_id   BIGINT UNSIGNED DEFAULT NULL,
  change_summary VARCHAR(500) DEFAULT NULL,
  created_by    BIGINT UNSIGNED DEFAULT NULL,
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_arv (report_id, version),
  KEY idx_arv_report (report_id),
  CONSTRAINT fk_arv_report FOREIGN KEY (report_id) REFERENCES audit_reports(id) ON DELETE CASCADE,
  CONSTRAINT fk_arv_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS audit_report_comments (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  report_id     BIGINT UNSIGNED NOT NULL,
  version       INT DEFAULT NULL,
  comment_type  ENUM('comment','correction_request','approval_note','rejection_note','auditor_reply')
                NOT NULL DEFAULT 'comment',
  comment       TEXT NOT NULL,
  section_ref   VARCHAR(255) DEFAULT NULL,
  field_ref     VARCHAR(150) DEFAULT NULL,
  severity      ENUM('info','minor','major','critical') NOT NULL DEFAULT 'info',
  is_resolved   BOOLEAN NOT NULL DEFAULT FALSE,
  resolved_by   BIGINT UNSIGNED DEFAULT NULL,
  resolved_at   DATETIME DEFAULT NULL,
  parent_id     BIGINT UNSIGNED DEFAULT NULL,
  created_by    BIGINT UNSIGNED NOT NULL,
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at    DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_arc_report (report_id),
  KEY idx_arc_type (comment_type),
  CONSTRAINT fk_arc_report FOREIGN KEY (report_id) REFERENCES audit_reports(id) ON DELETE CASCADE,
  CONSTRAINT fk_arc_parent FOREIGN KEY (parent_id) REFERENCES audit_report_comments(id) ON DELETE CASCADE,
  CONSTRAINT fk_arc_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_arc_resolved_by FOREIGN KEY (resolved_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS verifier_assignments (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  report_id   BIGINT UNSIGNED NOT NULL,
  verifier_id BIGINT UNSIGNED NOT NULL,
  assigned_by BIGINT UNSIGNED DEFAULT NULL,
  assigned_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  due_date    DATE DEFAULT NULL,
  status      ENUM('pending','in_review','completed','reassigned') NOT NULL DEFAULT 'pending',
  completed_at DATETIME DEFAULT NULL,
  remarks     TEXT,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_va (report_id, verifier_id),
  KEY idx_va_verifier (verifier_id),
  KEY idx_va_status (status),
  CONSTRAINT fk_va_report FOREIGN KEY (report_id) REFERENCES audit_reports(id) ON DELETE CASCADE,
  CONSTRAINT fk_va_verifier FOREIGN KEY (verifier_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_va_assigned_by FOREIGN KEY (assigned_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS verifier_comments (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  report_id   BIGINT UNSIGNED NOT NULL,
  verifier_id BIGINT UNSIGNED NOT NULL,
  action      ENUM('comment','approved','rejected','returned','verified') NOT NULL DEFAULT 'comment',
  comments    TEXT NOT NULL,
  reason      VARCHAR(500) DEFAULT NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_vc_report (report_id),
  KEY idx_vc_verifier (verifier_id),
  CONSTRAINT fk_vc_report FOREIGN KEY (report_id) REFERENCES audit_reports(id) ON DELETE CASCADE,
  CONSTRAINT fk_vc_verifier FOREIGN KEY (verifier_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
