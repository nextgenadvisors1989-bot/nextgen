-- 013_create_notifications.sql — in-app notifications, templates and channel delivery logs
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS notifications (
  id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid         VARCHAR(36) NOT NULL,
  user_id      BIGINT UNSIGNED NOT NULL,
  title        VARCHAR(255) NOT NULL,
  message      TEXT NOT NULL,
  type         ENUM('info','success','warning','error','action_required') NOT NULL DEFAULT 'info',
  category     ENUM('AUDIT','REPORT','PAYROLL','COMPLIANCE','EMPLOYEE','EMPLOYER','ACCOUNT','SYSTEM','REMINDER')
               NOT NULL DEFAULT 'SYSTEM',
  priority     ENUM('low','normal','high','urgent') NOT NULL DEFAULT 'normal',
  action_url   VARCHAR(500) DEFAULT NULL,
  action_label VARCHAR(100) DEFAULT NULL,
  entity_type  VARCHAR(50) DEFAULT NULL,
  entity_id    BIGINT UNSIGNED DEFAULT NULL,
  is_read      BOOLEAN NOT NULL DEFAULT FALSE,
  read_at      DATETIME DEFAULT NULL,
  email_sent   BOOLEAN NOT NULL DEFAULT FALSE,
  sms_sent     BOOLEAN NOT NULL DEFAULT FALSE,
  whatsapp_sent BOOLEAN NOT NULL DEFAULT FALSE,
  expires_at   DATETIME DEFAULT NULL,
  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at   DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_notif_uuid (uuid),
  KEY idx_notif_user (user_id, is_read),
  KEY idx_notif_created (created_at),
  KEY idx_notif_category (category),
  KEY idx_notif_entity (entity_type, entity_id),
  CONSTRAINT fk_notif_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS notification_templates (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  template_code  VARCHAR(100) NOT NULL,
  template_name  VARCHAR(200) NOT NULL,
  channel        ENUM('email','sms','whatsapp','in_app') NOT NULL,
  subject        VARCHAR(300) DEFAULT NULL,
  body_html      LONGTEXT,
  body_text      TEXT,
  variables_json JSON DEFAULT NULL COMMENT 'Declared merge variables for validation',
  locale         VARCHAR(10) NOT NULL DEFAULT 'en',
  is_active      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by     BIGINT UNSIGNED DEFAULT NULL,
  deleted_at     DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_nt (template_code, channel, locale),
  KEY idx_nt_channel (channel),
  KEY idx_nt_active (is_active),
  CONSTRAINT fk_nt_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS notification_logs (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  notification_id BIGINT UNSIGNED DEFAULT NULL,
  user_id       BIGINT UNSIGNED DEFAULT NULL,
  channel       ENUM('email','sms','whatsapp','in_app') NOT NULL,
  template_code VARCHAR(100) DEFAULT NULL,
  recipient     VARCHAR(255) NOT NULL,
  subject       VARCHAR(300) DEFAULT NULL,
  body          LONGTEXT,
  status        ENUM('queued','sent','delivered','failed','bounced','read') NOT NULL DEFAULT 'queued',
  provider      VARCHAR(50) DEFAULT NULL,
  provider_message_id VARCHAR(255) DEFAULT NULL,
  error_message TEXT,
  retry_count   INT NOT NULL DEFAULT 0,
  sent_at       DATETIME DEFAULT NULL,
  delivered_at  DATETIME DEFAULT NULL,
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_nl_user (user_id),
  KEY idx_nl_channel (channel),
  KEY idx_nl_status (status),
  KEY idx_nl_created (created_at),
  CONSTRAINT fk_nl_notification FOREIGN KEY (notification_id) REFERENCES notifications(id) ON DELETE SET NULL,
  CONSTRAINT fk_nl_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS email_logs (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  to_email           VARCHAR(1000) NOT NULL,
  cc_email           VARCHAR(1000) DEFAULT NULL,
  bcc_email          VARCHAR(1000) DEFAULT NULL,
  from_email         VARCHAR(255) DEFAULT NULL,
  subject            VARCHAR(500) NOT NULL,
  body_html          LONGTEXT,
  template_code      VARCHAR(100) DEFAULT NULL,
  entity_type        VARCHAR(50) DEFAULT NULL,
  entity_id          BIGINT UNSIGNED DEFAULT NULL,
  attachments_json   JSON DEFAULT NULL,
  status             ENUM('queued','sent','failed') NOT NULL DEFAULT 'queued',
  provider           VARCHAR(50) DEFAULT 'smtp',
  message_id         VARCHAR(255) DEFAULT NULL,
  error_message      TEXT,
  sent_by            BIGINT UNSIGNED DEFAULT NULL,
  sent_at            DATETIME DEFAULT NULL,
  created_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_el_to (to_email(191)),
  KEY idx_el_status (status),
  KEY idx_el_entity (entity_type, entity_id),
  KEY idx_el_created (created_at),
  CONSTRAINT fk_el_sent_by FOREIGN KEY (sent_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sms_logs (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  to_mobile          VARCHAR(20) NOT NULL,
  message            TEXT NOT NULL,
  template_code      VARCHAR(100) DEFAULT NULL,
  entity_type        VARCHAR(50) DEFAULT NULL,
  entity_id          BIGINT UNSIGNED DEFAULT NULL,
  message_type       ENUM('transactional','promotional','otp') NOT NULL DEFAULT 'transactional',
  status             ENUM('queued','sent','failed','delivered') NOT NULL DEFAULT 'queued',
  provider           VARCHAR(50) DEFAULT 'twilio',
  provider_message_id VARCHAR(255) DEFAULT NULL,
  segments           INT NOT NULL DEFAULT 1,
  cost               DECIMAL(10,4) DEFAULT NULL,
  error_message      TEXT,
  sent_by            BIGINT UNSIGNED DEFAULT NULL,
  sent_at            DATETIME DEFAULT NULL,
  created_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_sl_to (to_mobile),
  KEY idx_sl_status (status),
  KEY idx_sl_created (created_at),
  CONSTRAINT fk_sl_sent_by FOREIGN KEY (sent_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS whatsapp_logs (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  to_mobile          VARCHAR(20) NOT NULL,
  message            TEXT NOT NULL,
  media_url          VARCHAR(1000) DEFAULT NULL,
  template_code      VARCHAR(100) DEFAULT NULL,
  entity_type        VARCHAR(50) DEFAULT NULL,
  entity_id          BIGINT UNSIGNED DEFAULT NULL,
  status             ENUM('queued','sent','delivered','read','failed') NOT NULL DEFAULT 'queued',
  provider           VARCHAR(50) DEFAULT 'meta',
  provider_message_id VARCHAR(255) DEFAULT NULL,
  error_message      TEXT,
  sent_by            BIGINT UNSIGNED DEFAULT NULL,
  sent_at            DATETIME DEFAULT NULL,
  delivered_at       DATETIME DEFAULT NULL,
  created_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_wl_to (to_mobile),
  KEY idx_wl_status (status),
  KEY idx_wl_created (created_at),
  CONSTRAINT fk_wl_sent_by FOREIGN KEY (sent_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS notification_preferences (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id     BIGINT UNSIGNED NOT NULL,
  category    VARCHAR(50) NOT NULL,
  in_app      BOOLEAN NOT NULL DEFAULT TRUE,
  email       BOOLEAN NOT NULL DEFAULT TRUE,
  sms         BOOLEAN NOT NULL DEFAULT FALSE,
  whatsapp    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_np (user_id, category),
  CONSTRAINT fk_np_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
