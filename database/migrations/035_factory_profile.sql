-- 035 - Factory Profile: one per employer (the factory is the employer). Follows the client's "FACTORY Profile" sheet: identity and licences, people and
-- working pattern, officers, units, departments, holidays, area of the factory set-up, welfare facilities, treatment plants, and power, boiler and compressor details.
-- Repeating lists are kept as JSON arrays (validated on save), the single facts as columns.
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS employer_factory_profiles (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  employer_id BIGINT UNSIGNED NOT NULL,
  occupiers TEXT NULL,
  factory_licence_no VARCHAR(100) NULL,
  inspector_note VARCHAR(255) NULL,
  year_of_establishment DATE NULL,
  msme_registration VARCHAR(100) NULL,
  msme_status VARCHAR(30) NULL,
  management_representative VARCHAR(150) NULL,
  operation_representative VARCHAR(150) NULL,
  occupational_details VARCHAR(255) NULL,
  manpower_onroll INT NULL,
  manpower_male INT NULL,
  manpower_female INT NULL,
  working_hours TEXT NULL,
  weekly_holiday VARCHAR(100) NULL,
  benefits VARCHAR(500) NULL,
  safety_officer VARCHAR(200) NULL,
  labour_welfare_officer VARCHAR(200) NULL,
  survey_number VARCHAR(100) NULL,
  land_total VARCHAR(100) NULL,
  constructed_area_sqm DECIMAL(14,2) NULL,
  open_space_sqm DECIMAL(14,2) NULL,
  compound_spacing VARCHAR(255) NULL,
  connected_hp DECIMAL(12,2) NULL,
  transformer_kva VARCHAR(60) NULL,
  sanction_load_kva VARCHAR(60) NULL,
  surrender_load_kva VARCHAR(60) NULL,
  supply_demand_kva VARCHAR(60) NULL,
  electric_use_load_kva VARCHAR(60) NULL,
  electrical_load_units_day DECIMAL(12,2) NULL,
  compressor_live VARCHAR(100) NULL,
  compressor_standby VARCHAR(100) NULL,
  boiler_capacity VARCHAR(100) NULL,
  boiler_steam_per_day VARCHAR(100) NULL,
  boiler_pressure VARCHAR(60) NULL,
  dg_capacity VARCHAR(150) NULL,
  units_json LONGTEXT NULL,
  departments_json LONGTEXT NULL,
  holidays_json LONGTEXT NULL,
  areas_json LONGTEXT NULL,
  welfare_json LONGTEXT NULL,
  treatment_json LONGTEXT NULL,
  migrant_json LONGTEXT NULL,
  updated_by BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_efp_employer (employer_id),
  CONSTRAINT fk_efp_employer FOREIGN KEY (employer_id) REFERENCES employers (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
