-- 003_create_employers.sql — client companies, their units and departments
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS employers (
  id                             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid                           VARCHAR(36)  NOT NULL,
  company_name                   VARCHAR(255) NOT NULL,
  employer_code                  VARCHAR(50)  NOT NULL,
  gst_number                     VARCHAR(20)  DEFAULT NULL,
  pan_number                     VARCHAR(20)  DEFAULT NULL,
  cin_number                     VARCHAR(30)  DEFAULT NULL,
  industry_type                  VARCHAR(100) DEFAULT NULL,
  company_type                   VARCHAR(100) DEFAULT NULL,
  year_of_establishment          INT          DEFAULT NULL,
  website_url                    VARCHAR(255) DEFAULT NULL,
  email                          VARCHAR(255) DEFAULT NULL,
  phone                          VARCHAR(20)  DEFAULT NULL,
  mobile                         VARCHAR(20)  DEFAULT NULL,
  fax                            VARCHAR(20)  DEFAULT NULL,
  address_line_1                 VARCHAR(255) DEFAULT NULL,
  address_line_2                 VARCHAR(255) DEFAULT NULL,
  city                           VARCHAR(100) DEFAULT NULL,
  state                          VARCHAR(100) DEFAULT NULL,
  pincode                        VARCHAR(10)  DEFAULT NULL,
  country                        VARCHAR(100) NOT NULL DEFAULT 'India',
  contact_person_name            VARCHAR(200) DEFAULT NULL,
  contact_person_designation     VARCHAR(100) DEFAULT NULL,
  contact_person_email           VARCHAR(255) DEFAULT NULL,
  contact_person_mobile          VARCHAR(20)  DEFAULT NULL,
  contact_person_alternate_mobile VARCHAR(20) DEFAULT NULL,
  number_of_units                INT NOT NULL DEFAULT 1,
  approximate_employee_count     INT DEFAULT NULL,
  compliance_contact_person      VARCHAR(200) DEFAULT NULL,
  compliance_contact_email       VARCHAR(255) DEFAULT NULL,
  compliance_contact_phone       VARCHAR(20)  DEFAULT NULL,
  payroll_contact_person         VARCHAR(200) DEFAULT NULL,
  payroll_contact_email          VARCHAR(255) DEFAULT NULL,
  payroll_contact_phone          VARCHAR(20)  DEFAULT NULL,
  notes                          TEXT,
  status                         ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at                     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by                     BIGINT UNSIGNED DEFAULT NULL,
  updated_by                     BIGINT UNSIGNED DEFAULT NULL,
  deleted_at                     DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_employers_uuid (uuid),
  UNIQUE KEY uq_employers_code (employer_code),
  KEY idx_employers_company_name (company_name),
  KEY idx_employers_email (email),
  KEY idx_employers_state (state),
  KEY idx_employers_status (status),
  KEY idx_employers_deleted_at (deleted_at),
  CONSTRAINT fk_employers_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_employers_updated_by FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Links an employer-portal login (users row) to the employer account it administers.
CREATE TABLE IF NOT EXISTS employer_users (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  employer_id BIGINT UNSIGNED NOT NULL,
  user_id     BIGINT UNSIGNED NOT NULL,
  is_primary  BOOLEAN NOT NULL DEFAULT FALSE,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_employer_user (employer_id, user_id),
  CONSTRAINT fk_eu_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_eu_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS company_units (
  id                    BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  employer_id           BIGINT UNSIGNED NOT NULL,
  unit_name             VARCHAR(255) NOT NULL,
  unit_code             VARCHAR(50)  DEFAULT NULL,
  location              VARCHAR(255) DEFAULT NULL,
  address               TEXT,
  contact_person_name   VARCHAR(200) DEFAULT NULL,
  contact_person_email  VARCHAR(255) DEFAULT NULL,
  contact_person_phone  VARCHAR(20)  DEFAULT NULL,
  employee_count        INT DEFAULT NULL,
  status                ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at            DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at            DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at            DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_units_employer (employer_id),
  KEY idx_units_name (unit_name),
  CONSTRAINT fk_units_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS departments (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  employer_id       BIGINT UNSIGNED NOT NULL,
  unit_id           BIGINT UNSIGNED DEFAULT NULL,
  department_name   VARCHAR(255) NOT NULL,
  department_code   VARCHAR(50)  DEFAULT NULL,
  head_of_department VARCHAR(200) DEFAULT NULL,
  contact_email     VARCHAR(255) DEFAULT NULL,
  contact_phone     VARCHAR(20)  DEFAULT NULL,
  employee_count    INT DEFAULT NULL,
  status            ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at        DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_dept_employer (employer_id),
  KEY idx_dept_name (department_name),
  CONSTRAINT fk_dept_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_dept_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
