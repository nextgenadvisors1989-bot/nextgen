-- 016_create_calendar.sql — unified calendar across audits, permits, compliance and reminders
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS calendar_events (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid           VARCHAR(36) NOT NULL,
  title          VARCHAR(255) NOT NULL,
  description    TEXT,
  event_type     ENUM('AUDIT','AUDIT_END_MEETING','REPORT_DUE','COMPLIANCE_EXPIRY','PAYROLL_RUN',
                      'LEAVE','HOLIDAY','TRAINING','MEETING','INSPECTION','PERMIT_VALIDITY','REMINDER','OTHER')
                 NOT NULL DEFAULT 'AUDIT',
  employer_id    BIGINT UNSIGNED DEFAULT NULL,
  unit_id        BIGINT UNSIGNED DEFAULT NULL,
  assignment_id  BIGINT UNSIGNED DEFAULT NULL,
  auditor_id     BIGINT UNSIGNED DEFAULT NULL,
  created_by     BIGINT UNSIGNED DEFAULT NULL,
  start_datetime DATETIME NOT NULL,
  end_datetime   DATETIME DEFAULT NULL,
  all_day        BOOLEAN NOT NULL DEFAULT FALSE,
  location       VARCHAR(500) DEFAULT NULL,
  meeting_url    VARCHAR(500) DEFAULT NULL,
  attendees_json JSON DEFAULT NULL COMMENT 'array of user ids / email addresses',
  reminder_minutes INT DEFAULT NULL,
  reminder_sent  BOOLEAN NOT NULL DEFAULT FALSE,
  color          VARCHAR(20) DEFAULT NULL,
  priority       ENUM('Low','Medium','High','Urgent') NOT NULL DEFAULT 'Medium',
  status         ENUM('scheduled','completed','cancelled','rescheduled') NOT NULL DEFAULT 'scheduled',
  recurrence_rule VARCHAR(500) DEFAULT NULL,
  parent_event_id BIGINT UNSIGNED DEFAULT NULL,
  visibility     ENUM('private','participants','employer','all') NOT NULL DEFAULT 'participants',
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at     DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_calev_uuid (uuid),
  KEY idx_ce_start (start_datetime),
  KEY idx_ce_end (end_datetime),
  KEY idx_ce_type (event_type),
  KEY idx_ce_employer (employer_id),
  KEY idx_ce_auditor (auditor_id),
  KEY idx_ce_status (status),
  CONSTRAINT fk_ce_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE,
  CONSTRAINT fk_ce_unit FOREIGN KEY (unit_id) REFERENCES company_units(id) ON DELETE SET NULL,
  CONSTRAINT fk_ce_assignment FOREIGN KEY (assignment_id) REFERENCES audit_assignments(id) ON DELETE CASCADE,
  CONSTRAINT fk_ce_auditor FOREIGN KEY (auditor_id) REFERENCES auditors(id) ON DELETE SET NULL,
  CONSTRAINT fk_ce_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_ce_parent FOREIGN KEY (parent_event_id) REFERENCES calendar_events(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS holidays (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  employer_id BIGINT UNSIGNED DEFAULT NULL COMMENT 'NULL = platform-wide holiday calendar',
  holiday_name VARCHAR(200) NOT NULL,
  holiday_date DATE NOT NULL,
  year        SMALLINT UNSIGNED NOT NULL,
  holiday_type ENUM('National','State','Festival','Company','Optional') NOT NULL DEFAULT 'Company',
  is_paid     BOOLEAN NOT NULL DEFAULT TRUE,
  description VARCHAR(500) DEFAULT NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by  BIGINT UNSIGNED DEFAULT NULL,
  deleted_at  DATETIME DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_hol_employer (employer_id),
  KEY idx_hol_date (holiday_date),
  KEY idx_hol_year (year),
  CONSTRAINT fk_hol_employer FOREIGN KEY (employer_id) REFERENCES employers(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
