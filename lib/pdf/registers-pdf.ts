/**
 * Statutory payroll registers as PDFs: the wage register for a payroll run, the monthly attendance register
 * and the annual leave register - the three documents a labour inspector asks for.
 *
 * Each is scoped by the caller (an establishment reads only its own); this module only renders.
 */
import { query, queryOne, type RowDataPacket } from '@/lib/db/mysql';
import {
  COLORS, createPdf, letterhead, sectionHeading, keyValues, table, stampFooters, setFont, paragraph, spacer, renderPdf, type Doc,
} from '@/lib/pdf/base';
import { formatCurrency } from '@/lib/utils/formatting';
import { formatDateTime } from '@/lib/utils/dates';
import { monthLabel } from '@/lib/validations/payroll.validation';
import { generateWageRegisterRule11 } from '@/lib/pdf/wage-register-rule11';

export interface RegisterContext {
  generatedByName: string;
  generatedByRole: string;
  generatedAt?: Date;
  /** Wage register only: `rule-11-5` (default, the statutory landscape register) or `detailed` (earnings and deductions in two tables). */
  format?: 'rule-11-5' | 'detailed';
}

interface Company { name: string; addressLines: string[]; registrationLine: string }

async function companyOf(employerId: number): Promise<Company> {
  const employer = await queryOne<RowDataPacket>(
    'SELECT company_name, address_line_1, address_line_2, city, state, pincode, employer_code, gst_number FROM employers WHERE id = ?', [employerId]
  );
  if (!employer) return { name: 'Establishment', addressLines: [], registrationLine: '' };
  return {
    name: String(employer.company_name),
    addressLines: [
      [employer.address_line_1, employer.address_line_2].filter(Boolean).join(', '),
      [employer.city, employer.state, employer.pincode].filter(Boolean).join(' - '),
    ].filter(Boolean) as string[],
    registrationLine: [employer.employer_code, employer.gst_number ? `GSTIN ${employer.gst_number}` : ''].filter(Boolean).join('  |  '),
  };
}

const money = (value: unknown) => formatCurrency(Number(value ?? 0));
const num = (value: unknown) => String(Math.round(Number(value ?? 0) * 100) / 100);

function open(company: Company, title: string, subtitle: string, meta: { label: string; value: string }[], landscape = false): Doc {
  const doc = createPdf({ title: `${title} - ${subtitle}`, subject: subtitle, author: company.name }, { landscape });
  letterhead(doc, { companyName: company.name, addressLines: company.addressLines, registrationLine: company.registrationLine, documentTitle: title, subtitle, metaRows: meta });
  return doc;
}

function finish(doc: Doc, company: Company, ref: string, context: RegisterContext): Promise<Buffer> {
  spacer(doc, 8);
  paragraph(doc, `Generated by ${context.generatedByName} (${context.generatedByRole}) on ${formatDateTime(context.generatedAt ?? new Date())}.`, { size: 8 });
  stampFooters(doc, ({ index, total }) => ({ left: ref, center: company.name, right: `Page ${index} of ${total}` }));
  return renderPdf(doc);
}

/* ─────────────────────────────── wage register ─────────────────────────────── */

export async function generateWageRegisterPdf(runId: number, context: RegisterContext): Promise<Buffer | null> {
  if (context.format !== 'detailed') return generateWageRegisterRule11(runId, context);
  const run = await queryOne<RowDataPacket>('SELECT * FROM payroll_runs WHERE id = ? AND deleted_at IS NULL', [runId]);
  if (!run) return null;
  const rows = await query<RowDataPacket>(
    `SELECT p.*, e.name AS employee_name, e.employee_number, e.designation
       FROM payslips p JOIN employees e ON e.id = p.employee_id
      WHERE p.payroll_run_id = ? AND p.deleted_at IS NULL ORDER BY e.employee_number`, [runId]
  );
  const company = await companyOf(Number(run.employer_id));
  const period = monthLabel(Number(run.month), Number(run.year));
  const doc = open(company, 'Wage Register', period, [
    { label: 'Run no.', value: String(run.run_number) }, { label: 'Status', value: String(run.status) }, { label: 'Employees', value: String(rows.length) },
  ]);

  const sum = (key: string) => rows.reduce((total, row) => total + Number(row[key] ?? 0), 0);
  keyValues(doc, [
    { label: 'Establishment', value: company.name }, { label: 'Wage period', value: period },
    { label: 'Period', value: `${run.period_from ?? ''} to ${run.period_to ?? ''}` }, { label: 'Run status', value: String(run.status) },
  ], { columns: 2 });

  sectionHeading(doc, 'Earnings');
  table(doc, {
    columns: [
      { key: '_sr', label: 'S.No', width: 0.05, align: 'center' }, { key: 'employee_number', label: 'Emp no', width: 0.12 }, { key: 'employee_name', label: 'Name', width: 0.2 },
      { key: 'paid_days', label: 'Paid days', width: 0.07, align: 'right', render: (r) => num(r.paid_days) }, { key: 'basic', label: 'Basic', width: 0.1, align: 'right', render: (r) => money(r.basic) },
      { key: 'da', label: 'DA', width: 0.08, align: 'right', render: (r) => money(r.da) }, { key: 'hra', label: 'HRA', width: 0.09, align: 'right', render: (r) => money(r.hra) },
      { key: 'other', label: 'Other', width: 0.09, align: 'right', render: (r) => money(Number(r.ta) + Number(r.pa) + Number(r.ea) + Number(r.npba) + Number(r.other_allowances) + Number(r.bonus_amount) + Number(r.arrears_amount)) },
      { key: 'overtime_amount', label: 'Overtime', width: 0.08, align: 'right', render: (r) => money(r.overtime_amount) }, { key: 'gross_earnings', label: 'Gross', width: 0.12, align: 'right', render: (r) => money(r.gross_earnings) },
    ],
    rows: rows.map((row, index) => ({ ...row, _sr: index + 1 })), maxRows: 2000, empty: 'No payslips on this run.',
    footer: `Total gross earnings: ${money(sum('gross_earnings'))}`,
  });

  sectionHeading(doc, 'Deductions and net pay');
  table(doc, {
    columns: [
      { key: '_sr', label: 'S.No', width: 0.05, align: 'center' }, { key: 'employee_number', label: 'Emp no', width: 0.12 }, { key: 'employee_name', label: 'Name', width: 0.2 },
      { key: 'pf_employee', label: 'PF', width: 0.09, align: 'right', render: (r) => money(Number(r.pf_employee) + Number(r.vpf_amount)) }, { key: 'esi_employee', label: 'ESI', width: 0.08, align: 'right', render: (r) => money(r.esi_employee) },
      { key: 'professional_tax', label: 'PT', width: 0.07, align: 'right', render: (r) => money(r.professional_tax) }, { key: 'lwf_amount', label: 'LWF', width: 0.07, align: 'right', render: (r) => money(r.lwf_amount) },
      { key: 'other', label: 'Other', width: 0.1, align: 'right', render: (r) => money(Number(r.tds_amount) + Number(r.advance_deduction) + Number(r.canteen_deduction) + Number(r.other_deductions)) },
      { key: 'total_deductions', label: 'Total deductions', width: 0.1, align: 'right', render: (r) => money(r.total_deductions) }, { key: 'net_pay', label: 'Net pay', width: 0.12, align: 'right', render: (r) => money(r.net_pay) },
    ],
    rows: rows.map((row, index) => ({ ...row, _sr: index + 1 })), maxRows: 2000, empty: 'No payslips on this run.',
    footer: `Total deductions: ${money(sum('total_deductions'))}`,
  });

  spacer(doc, 6);
  setFont(doc, 10.5, { bold: true });
  doc.fillColor(COLORS.brand).text(`Net wages paid for ${period}: ${money(sum('net_pay'))}`, { align: 'right' });
  return finish(doc, company, String(run.run_number), context);
}

/* ───────────────────────────── attendance register ───────────────────────────── */

const CODES: Record<string, string> = {
  Present: 'P', Absent: 'A', 'Half Day': 'H', Leave: 'L', Holiday: 'HD', 'Weekly Off': 'W', 'On Duty': 'OD', Late: 'LT', 'Comp Off': 'CO',
};

export async function generateAttendanceRegisterPdf(employerId: number, month: number, year: number, context: RegisterContext): Promise<Buffer | null> {
  const employer = await queryOne<RowDataPacket>('SELECT id FROM employers WHERE id = ? AND deleted_at IS NULL', [employerId]);
  if (!employer) return null;
  const employees = await query<RowDataPacket>(
    `SELECT DISTINCT e.id, e.name, e.employee_number FROM employees e
      WHERE e.employer_id = ? AND e.deleted_at IS NULL
        AND (e.status = 'active' OR EXISTS (SELECT 1 FROM attendance a WHERE a.employee_id = e.id AND a.month = ? AND a.year = ?))
      ORDER BY e.employee_number`, [employerId, month, year]
  );
  const marks = await query<RowDataPacket>(
    'SELECT employee_id, DAY(attendance_date) AS day, status, overtime_hours FROM attendance WHERE employer_id = ? AND month = ? AND year = ? AND deleted_at IS NULL', [employerId, month, year]
  );
  const company = await companyOf(employerId);
  const daysInMonth = new Date(year, month, 0).getDate();
  const period = monthLabel(month, year);
  const doc = open(company, 'Attendance Register', period, [{ label: 'Month', value: period }, { label: 'Employees', value: String(employees.length) }]);

  const byEmployee = new Map<number, Map<number, string>>();
  const counts = new Map<number, Record<string, number>>();
  for (const mark of marks) {
    const id = Number(mark.employee_id);
    if (!byEmployee.has(id)) { byEmployee.set(id, new Map()); counts.set(id, {}); }
    byEmployee.get(id)!.set(Number(mark.day), CODES[String(mark.status)] ?? '?');
    const tally = counts.get(id)!;
    tally[String(mark.status)] = (tally[String(mark.status)] ?? 0) + 1;
  }

  keyValues(doc, [{ label: 'Establishment', value: company.name }, { label: 'Month', value: period }], { columns: 2 });
  setFont(doc, 8);
  doc.fillColor(COLORS.muted).text('P — Present   A — Absent   H — Half day   L — Leave   HD — Holiday   W — Weekly off   OD — On duty   LT — Late   CO — Comp off', { width: 495 });
  doc.moveDown(0.6);

  const halves: [number, number][] = [[1, Math.min(16, daysInMonth)]];
  if (daysInMonth > 16) halves.push([17, daysInMonth]);
  for (const [from, to] of halves) {
    sectionHeading(doc, `Days ${from}–${to}`);
    const dayColumns = Array.from({ length: to - from + 1 }, (_, i) => from + i);
    const dayWidth = 0.62 / 16;
    table(doc, {
      columns: [
        { key: 'employee_number', label: 'Emp no', width: 0.14 }, { key: 'employee_name', label: 'Name', width: 0.24 },
        ...dayColumns.map((day) => ({ key: `d${day}`, label: String(day), width: dayWidth, align: 'center' as const })),
      ],
      rows: employees.map((employee) => {
        const row: Record<string, unknown> = { employee_number: employee.employee_number, employee_name: employee.name };
        for (const day of dayColumns) row[`d${day}`] = byEmployee.get(Number(employee.id))?.get(day) ?? '';
        return row;
      }),
      maxRows: 2000, empty: 'No attendance marked for this month.',
    });
    spacer(doc, 6);
  }

  sectionHeading(doc, 'Monthly totals');
  const present = (tally: Record<string, number> = {}) => (tally.Present ?? 0) + (tally.Late ?? 0) + (tally['On Duty'] ?? 0) + (tally['Half Day'] ?? 0) / 2;
  const rows = employees.map((employee) => {
    const tally = counts.get(Number(employee.id)) ?? {};
    return { employee_number: employee.employee_number, employee_name: employee.name, present: num(present(tally)), absent: tally.Absent ?? 0, leave: tally.Leave ?? 0, off: (tally['Weekly Off'] ?? 0) + (tally.Holiday ?? 0) };
  });
  table(doc, {
    columns: [
      { key: 'employee_number', label: 'Emp no', width: 0.16 }, { key: 'employee_name', label: 'Name', width: 0.32 }, { key: 'present', label: 'Days present', width: 0.14, align: 'right' },
      { key: 'absent', label: 'Absent', width: 0.12, align: 'right' }, { key: 'leave', label: 'Leave', width: 0.12, align: 'right' }, { key: 'off', label: 'Off / holiday', width: 0.14, align: 'right' },
    ],
    rows, maxRows: 2000, empty: 'No employees.',
  });
  const totalPresent = employees.reduce((total, employee) => total + present(counts.get(Number(employee.id))), 0);
  spacer(doc, 6);
  setFont(doc, 10, { bold: true });
  doc.fillColor(COLORS.brand).text(`Man-days present in ${period}: ${num(totalPresent)}`, { align: 'right' });
  return finish(doc, company, `ATT/${year}/${String(month).padStart(2, '0')}`, context);
}

/* ─────────────────────────────── leave register ─────────────────────────────── */

export async function generateLeaveRegisterPdf(employerId: number, year: number, context: RegisterContext): Promise<Buffer | null> {
  const employer = await queryOne<RowDataPacket>('SELECT id FROM employers WHERE id = ? AND deleted_at IS NULL', [employerId]);
  if (!employer) return null;
  const rows = await query<RowDataPacket>(
    `SELECT e.employee_number, e.name AS employee_name, COALESCE(lt.name, 'Leave') AS leave_type, ll.opening_balance, ll.accrued, ll.availed, ll.encashed, ll.lapsed, ll.closing_balance
       FROM leave_ledgers ll JOIN employees e ON e.id = ll.employee_id LEFT JOIN leave_types lt ON lt.id = ll.leave_type_id
      WHERE ll.employer_id = ? AND ll.year = ? AND ll.deleted_at IS NULL ORDER BY e.employee_number, lt.name`, [employerId, year]
  );
  const company = await companyOf(employerId);
  const doc = open(company, 'Leave Register', `Year ${year}`, [{ label: 'Year', value: String(year) }, { label: 'Ledger lines', value: String(rows.length) }]);
  keyValues(doc, [{ label: 'Establishment', value: company.name }, { label: 'Year', value: String(year) }], { columns: 2 });
  sectionHeading(doc, 'Leave account by employee');
  table(doc, {
    columns: [
      { key: 'employee_number', label: 'Emp no', width: 0.12 }, { key: 'employee_name', label: 'Name', width: 0.22 }, { key: 'leave_type', label: 'Leave type', width: 0.16 },
      { key: 'opening_balance', label: 'Opening', width: 0.09, align: 'right', render: (r) => num(r.opening_balance) }, { key: 'accrued', label: 'Accrued', width: 0.09, align: 'right', render: (r) => num(r.accrued) },
      { key: 'availed', label: 'Availed', width: 0.09, align: 'right', render: (r) => num(r.availed) }, { key: 'encashed', label: 'Encashed', width: 0.09, align: 'right', render: (r) => num(r.encashed) },
      { key: 'lapsed', label: 'Lapsed', width: 0.07, align: 'right', render: (r) => num(r.lapsed) }, { key: 'closing_balance', label: 'Balance', width: 0.07, align: 'right', render: (r) => num(r.closing_balance) },
    ],
    rows, maxRows: 4000, empty: 'No leave has been accrued for this year.',
  });
  const total = (key: string) => rows.reduce((sum, row) => sum + Number(row[key] ?? 0), 0);
  spacer(doc, 6);
  setFont(doc, 10, { bold: true });
  doc.fillColor(COLORS.brand).text(`Days accrued in the year: ${num(total('accrued'))}   |   availed: ${num(total('availed'))}   |   balance: ${num(total('closing_balance'))}`, { align: 'right' });
  return finish(doc, company, `LVE/${year}`, context);
}
